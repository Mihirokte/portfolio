// Sync prep-portal data from the sibling swe-job-prep repo into this app.
// - 5 areas' drills.json  -> src/prep/data/drills.ts
// - problems-pack/pack_*.json (merged) -> src/prep/data/packs.ts
// - judge_harness.py -> public/prep/judge_harness.py (fetched by the worker)
// Run: node scripts/sync-prep-data.mjs   (override source with PREP_SRC env var)
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, existsSync } from 'node:fs'
import { resolve, join } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const SRC = process.env.PREP_SRC || resolve(ROOT, '../swe-job-prep')

const AREAS = [
  { key: 'dsa', label: 'DSA', dir: '01-dsa' },
  { key: 'lld', label: 'Low-Level Design', dir: '02-lld' },
  { key: 'arch', label: 'Architecture', dir: '03-architecture' },
  { key: 'sd', label: 'System Design', dir: '04-system-design' },
  { key: 'ai', label: 'AI Engineering', dir: '05-ai-engineering' },
]

const areas = AREAS.map((a) => ({
  key: a.key,
  label: a.label,
  drills: JSON.parse(readFileSync(join(SRC, a.dir, 'drills.json'), 'utf8')),
}))

const packDir = join(SRC, '01-dsa', 'problems-pack')
const packs = {}
if (existsSync(packDir)) {
  for (const f of readdirSync(packDir).filter((f) => /^pack_\d+\.json$/.test(f)).sort()) {
    for (const p of JSON.parse(readFileSync(join(packDir, f), 'utf8'))) packs[p.id] = p
  }
}

const dataDir = join(ROOT, 'src', 'prep', 'data')
mkdirSync(dataDir, { recursive: true })
writeFileSync(
  join(dataDir, 'drills.ts'),
  `// GENERATED by scripts/sync-prep-data.mjs — do not edit by hand.\n` +
    `import type { Area } from '../types'\n\n` +
    `export const AREAS: Area[] = ${JSON.stringify(areas, null, 1)}\n`,
)
writeFileSync(
  join(dataDir, 'packs.ts'),
  `// GENERATED by scripts/sync-prep-data.mjs — do not edit by hand.\n` +
    `import type { Problem } from '../types'\n\n` +
    `export const PACKS: Record<string, Problem> = ${JSON.stringify(packs, null, 1)}\n`,
)

mkdirSync(join(ROOT, 'public', 'prep'), { recursive: true })
copyFileSync(join(packDir, 'judge_harness.py'), join(ROOT, 'public', 'prep', 'judge_harness.py'))

const total = areas.reduce((n, a) => n + a.drills.length, 0)
console.log(`synced: ${total} drills across ${areas.length} areas, ${Object.keys(packs).length} runnable problems`)
